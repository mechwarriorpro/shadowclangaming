#!/usr/bin/env python3
"""Generate the combat-blast shader asset set.

One style in `warhead/BlastStyle.java` becomes three files:

    assets/shadowclangaming/post_effect/<name>.json        the pass list (what Minecraft runs)
    assets/shadowclangaming/shaders/program/post/<name>.json   the program binding
    assets/shadowclangaming/shaders/post/<name>.fsh         the GLSL

Run from the mod root after touching BlastStyle:  python3 tools/gen_blast_shaders.py

The fragment shaders are written from a small parameter set rather than kept as nine hand-edited copies,
because a typo in one of nine near-identical GLSL files is a failed compile that a player only discovers when
that specific warhead goes off.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "src/main/resources/assets/shadowclangaming")

# name, kind, colour (0..1), core, vignette, grain, chromatic
STYLES = [
    ("blast_flash", "flash", (1.00, 0.96, 0.86), 1.60, 0.55, 0.00, 0.0015),
    ("blast_fire", "fire", (1.00, 0.52, 0.16), 1.35, 0.65, 0.05, 0.0010),
    ("blast_rad", "rad", (0.72, 0.90, 0.42), 1.10, 0.80, 0.03, 0.0008),
    ("blast_emp", "emp", (0.50, 0.84, 1.00), 1.15, 0.40, 0.10, 0.0060),
    ("blast_toxic", "toxic", (0.44, 0.82, 0.34), 0.90, 0.95, 0.04, 0.0006),
    ("blast_frost", "frost", (0.64, 0.92, 1.00), 1.05, 0.85, 0.02, 0.0009),
    ("blast_void", "void", (0.70, 0.45, 1.00), 1.75, 1.10, 0.06, 0.0035),
    ("blast_coin", "coin", (1.00, 0.83, 0.30), 1.20, 0.50, 0.00, 0.0012),
    ("blast_fallback", "fallback", (1.00, 1.00, 1.00), 1.05, 0.60, 0.00, 0.0010),
]

FRAGMENT = """#version 150

// {name} - {kind} blast effect, generated by tools/gen_blast_shaders.py.
//
// Uniforms driven from Java (client/BlastShaderFx):
//   Strength  0..1, how hard this detonation is pushing right now
//   Time      seconds since the chain was built, for animation
uniform sampler2D DiffuseSampler;
uniform float Strength;
uniform float Time;

in vec2 texCoord;

out vec4 fragColor;

const vec3 TINT = vec3({r:.3f}, {g:.3f}, {b:.3f});

void main() {{
    vec2 uv = texCoord;
    vec2 d = uv - vec2(0.5);
    float r = length(d);

    // Chromatic split: the screen's colour channels come apart by a few pixels, which reads as "pressure"
    // rather than "someone turned the brightness up".
    float split = {chromatic:.5f} * Strength;
    vec3 color = vec3(
        texture(DiffuseSampler, uv + d * split).r,
        texture(DiffuseSampler, uv).g,
        texture(DiffuseSampler, uv - d * split).b);

    // Core flash: everything near the centre goes white-hot first.
    float core = (1.0 - smoothstep(0.0, 0.62, r));
    color += TINT * core * {core:.3f} * Strength;
    color = mix(color, vec3(1.0), clamp(Strength * core * 0.55, 0.0, 0.90));

    // Vignette: the edge of the screen takes the blast's colour, so even a distant hit is felt.
    float vignette = smoothstep(0.35, 0.95, r);
    color = mix(color, color * (1.0 - 0.35 * vignette) + TINT * vignette * {vignette:.3f} * Strength,
                clamp(Strength * 1.2, 0.0, 1.0));

    // Breathing motion: one slow pulse so a long effect does not look like a frozen filter.
    float breathe = 0.94 + 0.06 * sin(Time * {pulse:.1f} + r * 6.0);
    color *= mix(1.0, breathe, Strength);

    // Grain: a little noise hides banding on the big flat gradients.
    float grain = fract(sin(dot(uv * vec2(12.9898, 78.233) + Time,
                                vec2(1.0, 1.0))) * 43758.5453);
    color += (grain - 0.5) * {grain:.3f} * Strength;

    // Each style gets its own signature pass; colour alone is not a different effect.
    {special}

    fragColor = vec4(max(color, vec3(0.0)), 1.0);
}}
"""

PROGRAM = {
    # EffectInstance treats unqualified shader ids as minecraft:..., not this mod's namespace.
    "vertex": "shadowclangaming:post/apex_common",
    "samplers": [{"name": "DiffuseSampler"}],
    "uniforms": [
        {"name": "Strength", "type": "float", "count": 1, "values": [1.0]},
        {"name": "Time", "type": "float", "count": 1, "values": [0.0]},
    ],
}


def post_effect(name):
    return {
        "targets": ["swap"],
        "passes": [
            {
                "name": "shadowclangaming:post/" + name,
                "intarget": "minecraft:main",
                "outtarget": "swap",
                "uniforms": [
                    {"name": "Strength", "values": [1.0]},
                    {"name": "Time", "values": [0.0]},
                ],
            },
            {
                # A copy back into the main target: a pass cannot read and write minecraft:main at once.
                "name": "shadowclangaming:post/apex_copy",
                "intarget": "swap",
                "outtarget": "minecraft:main",
            },
        ],
    }


SPECIAL = {
    "flash": """float ring = 1.0 - smoothstep(0.0, 0.025, abs(r - mod(Time * 0.45, 0.85)));
    color = mix(color, vec3(1.0, 0.98, 0.86), ring * Strength * 0.55);""",
    "fire": """vec2 emberCell = floor(uv * vec2(46.0, 28.0) + vec2(0.0, -Time * 2.5));
    float emberHash = fract(sin(dot(emberCell, vec2(127.1, 311.7))) * 43758.5453);
    float ember = smoothstep(0.965, 1.0, emberHash) * (1.0 - smoothstep(0.0, 0.10, abs(fract(uv.y * 4.0 + Time * 0.18) - 0.5)));
    color += vec3(1.0, 0.22, 0.025) * ember * Strength * 1.6;""",
    "rad": """float pulse = 0.5 + 0.5 * sin(Time * 1.7 - r * 22.0);
    float radWave = (1.0 - smoothstep(0.0, 0.045, abs(fract(r * 7.0 - Time * 0.12) - 0.5)));
    color = mix(color, color * vec3(0.72, 1.12, 0.62), Strength * (0.18 + 0.22 * pulse));
    color += vec3(0.10, 0.38, 0.06) * radWave * Strength * 0.35;""",
    "emp": """float scan = 0.5 + 0.5 * sin(uv.y * 720.0 + Time * 16.0);
    color += vec3(0.08, 0.35, 0.62) * scan * Strength * 0.12;
    color.rb = mix(color.rb, color.br, Strength * 0.10);""",
    "toxic": """float crawl = 0.5 + 0.5 * sin(atan(d.y, d.x) * 11.0 + r * 34.0 - Time * 2.3);
    float edge = smoothstep(0.18, 0.70, r) * crawl;
    color = mix(color, color * vec3(0.66, 1.12, 0.57) + vec3(0.03, 0.12, 0.01), edge * Strength * 0.42);""",
    "frost": """vec2 cell = floor(uv * vec2(36.0, 24.0));
    float crystal = fract(sin(dot(cell, vec2(41.7, 289.3))) * 15731.743);
    float frostEdge = smoothstep(0.25, 0.86, r) * smoothstep(0.58, 0.92, crystal);
    color = mix(color, vec3(0.68, 0.91, 1.0), frostEdge * Strength * 0.42);""",
    "void": """float wave = 0.5 + 0.5 * sin(r * 25.0 - Time * 4.0);
    vec3 inverted = vec3(1.0 - color.b, 1.0 - color.r, 1.0 - color.g);
    color = mix(color, inverted, wave * Strength * 0.18);
    color += vec3(0.12, 0.025, 0.24) * wave * Strength * 0.16;""",
    "coin": """vec2 coinCell = floor(uv * vec2(34.0, 22.0));
    float sparkleHash = fract(sin(dot(coinCell, vec2(127.1, 311.7)) + floor(Time * 5.0)) * 43758.5453);
    float sparkle = smoothstep(0.94, 1.0, sparkleHash) * (0.65 + 0.35 * sin(Time * 8.0 + sparkleHash * 6.28));
    color += vec3(1.0, 0.72, 0.12) * sparkle * Strength * 0.85;""",
    "fallback": """float ring = 1.0 - smoothstep(0.0, 0.03, abs(r - mod(Time * 0.32, 0.9)));
    color = mix(color, vec3(1.0), ring * Strength * 0.22);""",
}


def main():
    os.makedirs(os.path.join(ASSETS, "shaders/post"), exist_ok=True)
    os.makedirs(os.path.join(ASSETS, "shaders/program/post"), exist_ok=True)
    os.makedirs(os.path.join(ASSETS, "post_effect"), exist_ok=True)

    for name, kind, (r, g, b), core, vignette, grain, chromatic in STYLES:
        # The pulse frequency differs a little per style so two overlapping styles never lock in phase.
        pulse = 2.0 + (len(kind) % 5) * 0.7
        text = FRAGMENT.format(name=name, kind=kind, r=r, g=g, b=b, core=core, vignette=vignette,
                               grain=grain, chromatic=chromatic, pulse=pulse, special=SPECIAL[kind])
        with open(os.path.join(ASSETS, "shaders/post", name + ".fsh"), "w", encoding="utf-8") as handle:
            handle.write(text)
        # In 1.21.1 EffectInstance resolves shader source from shaders/program/<id>.fsh.
        with open(os.path.join(ASSETS, "shaders/program/post", name + ".fsh"), "w", encoding="utf-8") as handle:
            handle.write(text)

        program = dict(PROGRAM)
        program["fragment"] = "shadowclangaming:post/" + name
        with open(os.path.join(ASSETS, "shaders/program/post", name + ".json"), "w",
                  encoding="utf-8") as handle:
            json.dump(program, handle, indent=2)
            handle.write("\n")

        with open(os.path.join(ASSETS, "post_effect", name + ".json"), "w", encoding="utf-8") as handle:
            json.dump(post_effect(name), handle, indent=2)
            handle.write("\n")

    print("%d blast shader styles written (3 files each)" % len(STYLES))
    return 0


if __name__ == "__main__":
    sys.exit(main())
